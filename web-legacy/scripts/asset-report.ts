/**
 * Art manifest report. `npm run assets:report` writes docs/ASSET_MANIFEST.md (the shot list for
 * Merlin) and prints delivered vs missing. `npm run assets:check` only prints, and exits 1 if any are missing.
 */
import { existsSync, writeFileSync } from "node:fs";
import { ART_EXTENSIONS, ART_MANIFEST, ART_SPECS } from "../src/assets/artManifest.ts";

const found = (e: (typeof ART_MANIFEST)[number]): string | null => {
  for (const ext of ART_EXTENSIONS) {
    const p = `public/assets/${e.dir}/${e.name}.${ext}`;
    if (existsSync(p)) return p;
  }
  return null;
};

const rows = ART_MANIFEST.map((e) => ({ e, file: found(e) }));
const missing = rows.filter((r) => !r.file);
console.log(`Art: ${rows.length - missing.length}/${rows.length} delivered`);
for (const r of missing) console.log(`  missing  public/assets/${r.e.dir}/${r.e.name}.webp   (${r.e.id})`);

if (process.argv.includes("--write")) {
  const lines = [
    "# Art shot list (generated, do not edit)",
    "",
    "Generated by `npm run assets:report` from `src/assets/artManifest.ts`. Edit the manifest, not this file.",
    "Style and handoff rules: `docs/ASSET_PIPELINE.md`.",
    "",
    `**${rows.length - missing.length}/${rows.length} delivered.**`,
    "",
  ];
  for (const kind of ["portrait", "panel", "background"] as const) {
    const group = rows.filter((r) => r.e.kind === kind);
    if (!group.length) continue;
    const s = ART_SPECS[kind];
    lines.push(`## ${kind}s: ${s.width}×${s.height}, ${s.formats}`, "", `_${s.note}_`, "", "| Done | Save as | Scene | Brief |", "|---|---|---|---|");
    for (const { e, file } of group) lines.push(`| ${file ? "✅" : "⬜"} | \`public/assets/${e.dir}/${e.name}.webp\` | ${e.scene} | ${e.brief.replace(/\|/g, "/")} |`);
    lines.push("");
  }
  writeFileSync("docs/ASSET_MANIFEST.md", lines.join("\n"));
  console.log("wrote docs/ASSET_MANIFEST.md");
}
if (process.argv.includes("--write")) {
  const STYLE =
    "Comic-book illustration: bold ink outlines, flat cel colors, halftone dot shading, in the style of the game Dispatch. " +
    "Palette: ink black, warm grey, brown, warm gold for lit windows. Teal (#00ffcc) is a small accent only (neon signs, glowing glyphs, the watch glow), never a wash over the image. " +
    "Setting: rainy Quiapo, Manila. Absolutely no text, lettering, captions, logos or speech bubbles anywhere in the image.";
  const CHARS: [RegExp, string, string][] = [
    [/Renzo/, "Renzo", "portraits/renzo"],
    [/Lola/, "Lola Rosa", "portraits/lola"],
    [/Dante/, "Dante", "portraits/dante"],
    [/Mang Domeng/, "Mang Domeng", "portraits/mang_domeng"],
    [/sacristan/i, "the sacristan", "portraits/sacristan"],
    [/runner/i, "the runner", "portraits/runner"],
  ];
  const out = [
    "# Gemini prompts for Merlin (generated, do not edit)",
    "",
    "Generated by `npm run assets:report` from `src/assets/artManifest.ts`. Only slots still missing are listed.",
    "",
    "## How to use",
    "1. Do the **portraits first**. Keep the approved portraits: attach them to Gemini as reference images for every panel that features that character, so faces stay consistent.",
    "2. For each slot below: paste the **Prompt** into Gemini, attach the listed reference images, generate, and pick the best result.",
    "3. Resize/crop to the stated size if Gemini returns a different one (panels must be 16:9).",
    "4. Save to the exact **Save as** path (webp preferred). Do not rename. Commit and push.",
    "5. Run `npm run assets:check` (or open `/?assets` in the dev server) to see what is left.",
    "",
    `**${missing.length} slots to generate.**`,
    "",
  ];
  for (const kind of ["portrait", "panel", "background"] as const) {
    const group = missing.filter((r) => r.e.kind === kind);
    if (!group.length) continue;
    const sp = ART_SPECS[kind];
    out.push(`## ${kind}s (${sp.width}×${sp.height})`, "");
    for (const { e } of group) {
      const refs = kind === "portrait" ? [] : CHARS.filter(([re, , path]) => re.test(e.brief) && path !== `${e.dir}/${e.name}`);
      const framing =
        kind === "portrait"
          ? "Square 1:1 head-and-shoulders bust, face centered, bold readable silhouette, plain or transparent background. It will be shown very small (72px), so keep shapes simple and lines strong."
          : kind === "panel"
            ? "Wide 16:9 comic panel. Keep the main subject centered with a ~12% safe margin (edges get cropped by a slanted mask). Keep the bottom 28% free of key detail (a dialogue box covers it)."
            : "Wide 16:9 full-bleed background, no characters in the lower third.";
      out.push(
        "### `" + e.id + "`",
        "- **Save as:** `public/assets/" + e.dir + "/" + e.name + ".webp`  (" + sp.width + "×" + sp.height + ")",
        "- **Used in:** " + e.scene,
        "- **Reference images to attach:** " + (refs.length ? refs.map(([, n, path]) => n + " (`public/assets/" + path + ".webp`)").join(", ") : "none"),
        "",
        "**Prompt:**",
        "```",
        e.brief,
        "",
        framing,
        "",
        STYLE + (refs.length ? " Match the attached reference images exactly for each character's face, hair, clothing and proportions." : ""),
        "```",
        "",
      );
    }
  }
  writeFileSync("docs/MERLIN_PROMPTS.md", out.join("\n"));
  console.log("wrote docs/MERLIN_PROMPTS.md");
}
if (process.argv.includes("--strict") && missing.length) process.exit(1);
