import { defineConfig, type Plugin } from "vite";

/**
 * Emits a minimal service worker next to the bundle. The precache list is the
 * hashed JS/CSS the build produced plus the shell, so the app starts offline
 * after the first visit. Everything else same-origin is cached as it is used.
 */
function serviceWorker(): Plugin {
  return {
    name: "balete-sw",
    apply: "build",
    generateBundle(_opts, bundle) {
      const version = Date.now().toString(36);
      const shell = ["./", "manifest.webmanifest", "icons/icon-192.png", "icons/icon-512.png"];
      const built = Object.keys(bundle).filter((f) => /\.(js|css)$/.test(f));
      const source = `// Generated by vite.config.ts
const CACHE = "balete-${version}";
const PRECACHE = ${JSON.stringify([...shell, ...built])};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    // Network first so updates land; fall back to the cached shell offline.
    e.respondWith(fetch(req).catch(() => caches.match("./")));
    return;
  }
  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
    )
  );
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

export default defineConfig({
  // Relative base so the build works from any sub-path (and the manifest scope "./").
  base: "./",
  plugins: [serviceWorker()],
  server: {
    host: true,
    port: 5173,
    open: false
  },
  build: {
    target: "esnext",
    sourcemap: true
  }
});
